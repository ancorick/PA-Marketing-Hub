// Netlify build step: generate the demo database once, compress it and embed it
// in the function bundle. It is published to Netlify Blobs only on the very first
// request of a fresh site; later deploys never overwrite live data.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mh-seed-'));
process.env.MH_SERVERLESS = '1';            // single-file database (no WAL)
process.env.MH_DATA_DIR = tmp;
process.env.MH_SEED_SCALE ||= '0.5';        // lighter demo: smaller snapshot, faster saves
process.env.MH_SEED_NEWSLETTER_MONTHS ||= '6';
process.env.NODE_ENV ||= 'production';

const imp = (p) => import(pathToFileURL(path.join(root, 'server', 'src', p)).href);
const { openDb, closeDb, db } = await imp('db.js');
const { config } = await imp('config.js');
openDb(config.dbFile);
const { seed } = await imp('seed/index.js');
await seed();
(await imp('db.js')).db.exec('DELETE FROM raw_records WHERE id NOT IN (SELECT MAX(id) FROM raw_records GROUP BY source, endpoint); VACUUM;');
closeDb();
void db;

const raw = fs.readFileSync(config.dbFile);
const gz = zlib.gzipSync(raw, { level: 9 });
const outDir = path.join(root, 'netlify', 'generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'seed-snapshot.mjs'), `// Generated by scripts/build-netlify-seed.mjs. Do not edit.\nexport default ${JSON.stringify(gz.toString('base64'))};\n`);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`[netlify] demo snapshot: ${(raw.length / 1e6).toFixed(1)} MB raw, ${(gz.length / 1e6).toFixed(2)} MB compressed`);
